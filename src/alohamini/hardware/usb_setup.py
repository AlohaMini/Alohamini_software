"""Bind left/right USB controllers by insertion order without opening motor ports."""

from __future__ import annotations

import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import time
from dataclasses import asdict, dataclass
from pathlib import Path

from alohamini.calibration.reference import json_bytes, save_bundle
from alohamini.paths import WorkspacePaths

# The uaccess tag must precede systemd's 73-seat-late.rules.
_RULES_DIRECTORY = Path("/etc/udev/rules.d")


@dataclass(frozen=True)
class USBController:
    serial_number: str
    vid: int
    pid: int

    def __post_init__(self):
        if not isinstance(self.serial_number, str) or not re.fullmatch(
            r"[A-Za-z0-9_.:-]{1,128}", self.serial_number
        ):
            raise ValueError("USB controller needs a unique, printable serial number")
        if any(type(v) is not int or not 0 <= v <= 65535 for v in (self.vid, self.pid)):
            raise ValueError("USB controller needs valid vendor/product IDs")


def usb_ports():
    from serial.tools import list_ports

    return {
        str(Path(port.device).resolve()): port
        for port in list_ports.comports(include_links=False)
        if port.vid is not None and port.pid is not None
    }


def _wait_added(previous, *, timeout_s=120):
    deadline = time.monotonic() + timeout_s
    stable, count = None, 0
    while time.monotonic() < deadline:
        current = usb_ports()
        if not previous.keys() <= current.keys():
            raise ValueError("A connected USB controller disappeared; reconnect and retry")
        added = current.keys() - previous.keys()
        if len(added) > 1:
            raise ValueError("More than one USB serial port appeared; insert one arm at a time")
        candidate = next(iter(added), None)
        port = current[candidate] if candidate is not None else None
        signature = (
            (candidate, port.serial_number, port.vid, port.pid) if port is not None else None
        )
        count = count + 1 if signature is not None and signature == stable else 0
        stable = signature
        if count >= 2:
            # Validate only the newly inserted board; unrelated USB devices may
            # lack serials. Never fall back to a transient /dev/ttyACM index.
            identity = USBController(port.serial_number, port.vid, port.pid)
            if any(
                (p.serial_number, p.vid, p.pid)
                == (identity.serial_number, identity.vid, identity.pid)
                for p in previous.values()
            ):
                raise ValueError(
                    "USB controllers have duplicate serial numbers; cannot bind safely"
                )
            return current, identity
        time.sleep(0.25)
    raise TimeoutError("USB insertion timed out; connect one controller and retry")


def capture_bindings(role):
    if not sys.stdin.isatty():
        raise RuntimeError("First USB setup requires an interactive terminal")
    print("Stop Host and teleoperation. Secure both arms before disconnecting USB.")
    response = input(
        f"Unplug both {role} USB controllers, then press ENTER (any other input cancels): "
    )
    if response.strip():
        raise InterruptedError("USB setup cancelled; no rules installed")
    current, bindings = usb_ports(), {}
    for side in ("left", "right"):
        print(f"Connect the {side} {role} USB controller and wait for detection.", flush=True)
        current, bindings[side] = _wait_added(current)
        print(f"{side.capitalize()} {role} detected: {bindings[side].serial_number}", flush=True)
    return bindings


def render_rules(role, bindings):
    if role not in ("leader", "follower") or set(bindings) != {"left", "right"}:
        raise ValueError("Provide one left/right binding for leader or follower")
    if bindings["left"] == bindings["right"]:
        raise ValueError("Left and right USB controllers must have distinct serial numbers")
    lines = ["# AlohaMini USB identities; generated by alohamini calibrate."]
    for side in ("left", "right"):
        board = bindings[side]
        lines.append(
            f'SUBSYSTEM=="tty", ATTRS{{idVendor}}=="{board.vid:04x}", '
            f'ATTRS{{idProduct}}=="{board.pid:04x}", ATTRS{{serial}}=="{board.serial_number}", '
            f'SYMLINK+="am_arm_{role}_{side}", GROUP="dialout", MODE="0660", TAG+="uaccess"'
        )
    return ("\n".join(lines) + "\n").encode()


def _binding_document(bindings):
    return dict(
        schema_version=1,
        role="leader",
        sides={side: asdict(board) for side, board in bindings.items()},
    )


def _pair_key(bindings):
    return hashlib.sha256(
        json.dumps(_binding_document(bindings), sort_keys=True).encode()
    ).hexdigest()[:20]


def _known_leaders(directory):
    paths = [directory / "leader.json", *sorted((directory / "leaders").glob("*.json"))]
    known = {}
    for path in paths:
        if path.exists():
            bindings = _load_bindings(path, "leader")
            known[_pair_key(bindings)] = bindings
    return known


def _leader_rules(known):
    identities, lines = {}, []
    for _, bindings in sorted(known.items()):
        for side, board in bindings.items():
            previous = identities.setdefault(board, side)
            if previous != side:
                raise ValueError(
                    "A USB controller cannot be registered as both left and right leader"
                )
        for line in render_rules("leader", bindings).decode().splitlines():
            if line not in lines:
                lines.append(line)
    return ("\n".join(lines) + "\n").encode()


def preserve_legacy_leader_calibration(workspace, leader_id):
    """Copy the old flat files to their recorded USB pair exactly once."""
    directory = workspace.calibration / "devices"
    anchor = directory / "leader-legacy.json"
    active = directory / "leader.json"
    sources = [
        workspace.calibration_file("teleoperators", f"{leader_id}_{side}")
        for side in ("left", "right")
    ]
    if not all(path.exists() for path in sources) or not active.exists():
        return
    if anchor.exists():
        bindings = _load_bindings(anchor, "leader")
    else:
        if any((directory / "leaders").glob("*.json")):
            # A new registry cannot establish which device produced older flat files.
            return
        bindings = _load_bindings(active, "leader")
    target = workspace.calibration / "teleoperators" / "usb" / _pair_key(bindings)
    destinations = [target / path.name for path in sources]
    if any(path.exists() for path in destinations):
        if not all(path.exists() for path in destinations):
            raise ValueError(f"Incomplete leader calibration: {target}")
        if not anchor.exists():
            save_bundle({anchor: json_bytes(_binding_document(bindings))}, {})
        return
    payloads = {anchor: json_bytes(_binding_document(bindings))}
    for source, destination in zip(sources, destinations, strict=True):
        if source.is_symlink():
            raise ValueError("Use a shared calibration directory, not a linked JSON file")
        payloads[destination] = source.read_bytes()
        reference = source.with_name(f"{source.stem}.reference.json")
        if reference.exists():
            payloads[target / reference.name] = reference.read_bytes()
    save_bundle(payloads, {})


def leader_calibration_directory(workspace, leader_id, ports, active_sides=("left", "right")):
    """Resolve connected USB identities without opening a motor port or changing zero."""
    available = usb_ports()
    present = {side: available.get(str(Path(ports[side]).resolve())) for side in active_sides}
    legacy = workspace.calibration / "teleoperators"
    if not present or all(port is None for port in present.values()):
        return legacy  # Explicit non-USB ports retain their supplied legacy configuration.
    if any(port is None for port in present.values()):
        raise ValueError("Connect both USB controllers for the current leader")
    identities = {
        side: USBController(port.serial_number, port.vid, port.pid)
        for side, port in present.items()
    }
    known = _known_leaders(workspace.calibration / "devices")
    matches = [
        pair
        for pair in known.values()
        if all(pair[side] == board for side, board in identities.items())
    ]
    if not matches:
        raise ValueError("Connected leader is not registered; run alohamini calibrate leader")
    if len(matches) != 1:
        raise ValueError(
            "This arm belongs to multiple leader pairs; connect both or specify calibration_dir"
        )
    preserve_legacy_leader_calibration(workspace, leader_id)
    return legacy / "usb" / _pair_key(matches[0])


def _ensure_leader_ports(workspace, aliases):
    directory = workspace.calibration / "devices"
    known = _known_leaders(directory)
    available = usb_ports()
    matches = []
    for bindings in known.values():
        try:
            matched = _matched_ports(bindings, available)
        except ValueError:
            continue
        matches.append((bindings, matched))
    if len(matches) > 1:
        raise ValueError(
            "Multiple registered leader pairs connected; connect only one or specify both ports"
        )
    if matches:
        bindings, matched = matches[0]
    else:
        if all(alias.exists() for alias in aliases.values()) and not known:
            selected = {
                side: available.get(str(alias.resolve())) for side, alias in aliases.items()
            }
            if all(port is not None for port in selected.values()):
                bindings = {
                    side: USBController(port.serial_number, port.vid, port.pid)
                    for side, port in selected.items()
                }
            else:
                bindings = capture_bindings("leader")
        else:
            if known:
                print(
                    "New leader USB controllers detected. "
                    "Register this pair; existing calibrations are kept."
                )
            bindings = capture_bindings("leader")
        matched = _matched_ports(bindings, usb_ports())
    known[_pair_key(bindings)] = bindings
    rules = _leader_rules(known)
    prepared = directory / "leader.rules"
    payloads = {directory / "leader.json": json_bytes(_binding_document(bindings)), prepared: rules}
    anchor = directory / "leader-legacy.json"
    active = directory / "leader.json"
    if active.exists() and not anchor.exists() and not any((directory / "leaders").glob("*.json")):
        payloads[anchor] = json_bytes(_binding_document(_load_bindings(active, "leader")))
    payloads.update(
        {
            directory / "leaders" / f"{key}.json": json_bytes(_binding_document(pair))
            for key, pair in known.items()
        }
    )
    changed = {
        path: content
        for path, content in payloads.items()
        if not path.exists() or path.read_bytes() != content
    }
    if changed:
        save_bundle(changed, {})
    if not _rules_installed("leader", rules) or any(
        not alias.exists() or alias.resolve() != Path(matched[side]).resolve()
        for side, alias in aliases.items()
    ):
        _install_rules("leader", prepared, matched, aliases, directory)
    return tuple(str(aliases[side]) for side in ("left", "right"))


def _matched_ports(bindings, ports):
    matched = {}
    for side, identity in bindings.items():
        matches = [
            path
            for path, port in ports.items()
            if (port.serial_number, port.vid, port.pid)
            == (identity.serial_number, identity.vid, identity.pid)
        ]
        if len(matches) != 1:
            raise ValueError(f"Connect the saved {side} USB controller ({identity.serial_number})")
        matched[side] = matches[0]
    return matched


def _rules_installed(role, rules):
    destination = _RULES_DIRECTORY / f"70-alohamini-{role}.rules"
    legacy = _RULES_DIRECTORY / f"90-alohamini-{role}.rules"
    return destination.exists() and destination.read_bytes() == rules and not legacy.exists()


def _install_rules(role, prepared, matched, aliases, backup_dir):
    udevadm = shutil.which("udevadm")
    if udevadm is None:
        raise RuntimeError(f"udevadm is required on Linux; generated rules: {prepared}")
    prefix = [] if os.geteuid() == 0 else [shutil.which("sudo") or "sudo"]
    destination = _RULES_DIRECTORY / f"70-alohamini-{role}.rules"
    legacy = _RULES_DIRECTORY / f"90-alohamini-{role}.rules"
    for previous in (destination, legacy):
        if previous.exists() and (
            previous == legacy or previous.read_bytes() != prepared.read_bytes()
        ):
            backup = backup_dir / f"{previous.stem}.{time.time_ns()}.backup.rules"
            backup.write_bytes(previous.read_bytes())
    print(
        f"Installing USB aliases: {destination}; sudo may request your system password.", flush=True
    )
    subprocess.run(
        [
            *prefix,
            "install",
            "-o",
            "root",
            "-g",
            "root",
            "-m",
            "0644",
            "--",
            str(prepared),
            str(destination),
        ],
        check=True,
    )
    if legacy.exists():
        subprocess.run([*prefix, "rm", "--", str(legacy)], check=True)
    subprocess.run([*prefix, udevadm, "control", "--reload-rules"], check=True)
    for port in matched.values():
        subprocess.run(
            [
                *prefix,
                udevadm,
                "trigger",
                "--action=add",
                "--subsystem-match=tty",
                f"--sysname-match={Path(port).name}",
            ],
            check=True,
        )
    subprocess.run([udevadm, "settle", "--timeout=10"], check=True)
    for side, alias in aliases.items():
        if not alias.exists() or alias.resolve() != Path(matched[side]).resolve():
            raise RuntimeError(f"USB alias was not created correctly: {alias}; rules: {prepared}")


def ensure_arm_ports(role, *, workspace=None, device_dir=Path("/dev")):
    """Reuse installed aliases, or capture, persist and install missing USB identities."""
    if role not in ("leader", "follower"):
        raise ValueError("USB role must be leader or follower")
    if sys.platform != "linux":
        raise RuntimeError("Automatic USB aliases require Linux; specify both serial ports")
    aliases = {side: device_dir / f"am_arm_{role}_{side}" for side in ("left", "right")}
    if role == "leader":
        return _ensure_leader_ports(workspace or WorkspacePaths(), aliases)
    directory = (workspace or WorkspacePaths()).calibration / "devices"
    path = directory / f"{role}.json"
    available = usb_ports()
    if path.exists():
        bindings = _load_bindings(path, role)
    elif all(alias.exists() for alias in aliases.values()):
        if aliases["left"].resolve() == aliases["right"].resolve():
            raise ValueError("Left and right USB aliases point to the same controller")
        selected = {side: available.get(str(alias.resolve())) for side, alias in aliases.items()}
        if any(port is None for port in selected.values()):
            raise ValueError("USB aliases must identify USB controllers; specify both serial ports")
        bindings = {
            side: USBController(port.serial_number, port.vid, port.pid)
            for side, port in selected.items()
        }
    else:
        bindings = capture_bindings(role)
        available = usb_ports()
    rules = render_rules(role, bindings)
    matched = _matched_ports(bindings, available)
    prepared = directory / f"{role}.rules"
    payloads = {
        path: json_bytes(
            dict(
                schema_version=1,
                role=role,
                sides={side: asdict(board) for side, board in bindings.items()},
            )
        ),
        prepared: rules,
    }
    changed = {
        file: content
        for file, content in payloads.items()
        if not file.exists() or file.read_bytes() != content
    }
    if changed:
        save_bundle(changed, {})
    if not _rules_installed(role, rules) or any(
        not alias.exists() or alias.resolve() != Path(matched[side]).resolve()
        for side, alias in aliases.items()
    ):
        _install_rules(role, prepared, matched, aliases, directory)
    return tuple(str(aliases[side]) for side in ("left", "right"))


def _load_bindings(path, role):
    data = json.loads(path.read_text())
    if (
        not isinstance(data, dict)
        or type(data.get("schema_version")) is not int
        or data["schema_version"] != 1
        or data.get("role") != role
        or not isinstance(data.get("sides"), dict)
        or set(data["sides"]) != {"left", "right"}
    ):
        raise ValueError(f"Invalid saved USB identity: {path}")
    try:
        bindings = {side: USBController(**row) for side, row in data["sides"].items()}
    except TypeError as error:
        raise ValueError(f"Invalid saved USB identity: {path}") from error
    render_rules(role, bindings)
    return bindings
