"""Bind left/right USB controllers by insertion order without opening motor ports."""

from __future__ import annotations

import os
import re
import shutil
import subprocess
import sys
import time
from dataclasses import asdict, dataclass
from pathlib import Path

from alohamini.calibration.reference import json_bytes, save_bundle
from alohamini.paths import WorkspacePaths


@dataclass(frozen=True)
class USBController:
    serial_number: str
    vid: int
    pid: int

    def __post_init__(self):
        if not isinstance(self.serial_number, str) or not re.fullmatch(
            r"[A-Za-z0-9_.:-]{1,128}", self.serial_number
        ):
            raise ValueError("USB controller needs a unique, printable serial number")
        if any(type(v) is not int or not 0 <= v <= 65535 for v in (self.vid, self.pid)):
            raise ValueError("USB controller needs valid vendor/product IDs")


def usb_ports():
    from serial.tools import list_ports

    return {
        str(Path(port.device).resolve()): port
        for port in list_ports.comports(include_links=False)
        if port.vid is not None and port.pid is not None
    }


def _wait_added(previous, *, timeout_s=120):
    deadline = time.monotonic() + timeout_s
    stable, count = None, 0
    while time.monotonic() < deadline:
        current = usb_ports()
        if not previous.keys() <= current.keys():
            raise ValueError("A connected USB controller disappeared; reconnect and retry")
        added = current.keys() - previous.keys()
        if len(added) > 1:
            raise ValueError("More than one USB serial port appeared; insert one arm at a time")
        candidate = next(iter(added), None)
        port = current[candidate] if candidate is not None else None
        signature = (
            (candidate, port.serial_number, port.vid, port.pid) if port is not None else None
        )
        count = count + 1 if signature is not None and signature == stable else 0
        stable = signature
        if count >= 2:
            # Validate only the newly inserted board; unrelated USB devices may
            # lack serials. Never fall back to a transient /dev/ttyACM index.
            identity = USBController(port.serial_number, port.vid, port.pid)
            if any(
                (p.serial_number, p.vid, p.pid)
                == (identity.serial_number, identity.vid, identity.pid)
                for p in previous.values()
            ):
                raise ValueError(
                    "USB controllers have duplicate serial numbers; cannot bind safely"
                )
            return current, identity
        time.sleep(0.25)
    raise TimeoutError("USB insertion timed out; connect one controller and retry")


def capture_bindings(role):
    if not sys.stdin.isatty():
        raise RuntimeError("First USB setup requires an interactive terminal")
    print("Stop programs using the arms. Support the arms and lift before unplugging USB.")
    response = input(f"Disconnect BOTH {role} USB cables, then press ENTER: ")
    if response.strip():
        raise InterruptedError("USB setup cancelled; no rules installed")
    current, bindings = usb_ports(), {}
    for side in ("left", "right"):
        print(f"Plug in the {side.upper()} {role} USB now; detection is automatic.", flush=True)
        current, bindings[side] = _wait_added(current)
        print(f"{side}: USB serial {bindings[side].serial_number}", flush=True)
    return bindings


def render_rules(role, bindings):
    if role not in ("leader", "follower") or set(bindings) != {"left", "right"}:
        raise ValueError("Provide one left/right binding for leader or follower")
    if bindings["left"] == bindings["right"]:
        raise ValueError("Left and right USB controllers must have distinct serial numbers")
    lines = ["# AlohaMini USB identities; generated by alohamini calibrate."]
    for side in ("left", "right"):
        board = bindings[side]
        lines.append(
            f'SUBSYSTEM=="tty", ATTRS{{idVendor}}=="{board.vid:04x}", '
            f'ATTRS{{idProduct}}=="{board.pid:04x}", ATTRS{{serial}}=="{board.serial_number}", '
            f'SYMLINK+="am_arm_{role}_{side}", GROUP="dialout", MODE="0660"'
        )
    return ("\n".join(lines) + "\n").encode()


def _matched_ports(bindings, ports):
    matched = {}
    for side, identity in bindings.items():
        matches = [
            path
            for path, port in ports.items()
            if (port.serial_number, port.vid, port.pid)
            == (identity.serial_number, identity.vid, identity.pid)
        ]
        if len(matches) != 1:
            raise ValueError(f"Connect the saved {side} USB controller ({identity.serial_number})")
        matched[side] = matches[0]
    return matched


def _install_rules(role, prepared, matched, aliases, backup_dir):
    udevadm = shutil.which("udevadm")
    if udevadm is None:
        raise RuntimeError(f"udevadm is required on Linux; generated rules: {prepared}")
    prefix = [] if os.geteuid() == 0 else [shutil.which("sudo") or "sudo"]
    destination = Path(f"/etc/udev/rules.d/90-alohamini-{role}.rules")
    if destination.exists() and destination.read_bytes() != prepared.read_bytes():
        backup = backup_dir / f"{destination.stem}.{time.time_ns()}.backup.rules"
        backup.write_bytes(destination.read_bytes())
    print(f"Install USB aliases: {destination}; sudo may request your system password.", flush=True)
    subprocess.run(
        [
            *prefix,
            "install",
            "-o",
            "root",
            "-g",
            "root",
            "-m",
            "0644",
            "--",
            str(prepared),
            str(destination),
        ],
        check=True,
    )
    subprocess.run([*prefix, udevadm, "control", "--reload-rules"], check=True)
    for port in matched.values():
        subprocess.run(
            [
                *prefix,
                udevadm,
                "trigger",
                "--action=add",
                "--subsystem-match=tty",
                f"--sysname-match={Path(port).name}",
            ],
            check=True,
        )
    subprocess.run([udevadm, "settle", "--timeout=10"], check=True)
    for side, alias in aliases.items():
        if not alias.exists() or alias.resolve() != Path(matched[side]).resolve():
            raise RuntimeError(f"USB alias was not created correctly: {alias}; rules: {prepared}")


def ensure_arm_ports(role, *, workspace=None, device_dir=Path("/dev")):
    """Reuse installed aliases, or capture, persist and install missing USB identities."""
    if role not in ("leader", "follower"):
        raise ValueError("USB role must be leader or follower")
    if sys.platform != "linux":
        raise RuntimeError("Automatic USB aliases require Linux; specify both serial ports")
    aliases = {side: device_dir / f"am_arm_{role}_{side}" for side in ("left", "right")}
    directory = (workspace or WorkspacePaths()).calibration / "devices"
    path = directory / f"{role}.json"
    if all(alias.exists() for alias in aliases.values()):
        if aliases["left"].resolve() == aliases["right"].resolve():
            raise ValueError("Left and right USB aliases point to the same controller")
        if path.exists():
            bindings = _load_bindings(path, role)
            matched = _matched_ports(bindings, usb_ports())
            if any(aliases[side].resolve() != Path(matched[side]).resolve() for side in aliases):
                raise ValueError("USB aliases differ from saved left/right identities")
        return tuple(str(aliases[side]) for side in ("left", "right"))
    if path.exists():
        bindings = _load_bindings(path, role)
    else:
        bindings = capture_bindings(role)
    rules = render_rules(role, bindings)
    matched = _matched_ports(bindings, usb_ports())
    prepared = directory / f"{role}.rules"
    save_bundle(
        {
            path: json_bytes(
                dict(
                    schema_version=1,
                    role=role,
                    sides={side: asdict(board) for side, board in bindings.items()},
                )
            ),
            prepared: rules,
        },
        {},
    )
    _install_rules(role, prepared, matched, aliases, directory)
    return tuple(str(aliases[side]) for side in ("left", "right"))


def _load_bindings(path, role):
    import json

    data = json.loads(path.read_text())
    if (
        not isinstance(data, dict)
        or type(data.get("schema_version")) is not int
        or data["schema_version"] != 1
        or data.get("role") != role
        or not isinstance(data.get("sides"), dict)
        or set(data["sides"]) != {"left", "right"}
    ):
        raise ValueError(f"Invalid saved USB identity: {path}")
    try:
        bindings = {side: USBController(**row) for side, row in data["sides"].items()}
    except TypeError as error:
        raise ValueError(f"Invalid saved USB identity: {path}") from error
    render_rules(role, bindings)
    return bindings
